#!/usr/bin/env python3
"""生成默认的开关旋钮 PNG：64×64 白色抗锯齿圆。

旋钮图标作为主题资源在运行时加载，不嵌入可执行文件。

用法：
    python3 tools/gen_switch_icon.py --png assets/Default/icon/knob.png

调试时也可以用 -o 额外输出一份 C 数据。
"""

from __future__ import annotations

import argparse
import struct
import sys
import zlib
from pathlib import Path

WIDTH = 64
HEIGHT = 64
RADIUS = 32.0
SUPERSAMPLE = 4


def build_pixels() -> bytes:
    data = bytearray()
    step = 1.0 / SUPERSAMPLE
    samples = SUPERSAMPLE * SUPERSAMPLE
    for y in range(HEIGHT):
        for x in range(WIDTH):
            inside = 0
            for sy in range(SUPERSAMPLE):
                py = y + (sy + 0.5) * step
                dy = py - HEIGHT / 2.0
                for sx in range(SUPERSAMPLE):
                    px = x + (sx + 0.5) * step
                    dx = px - WIDTH / 2.0
                    if dx * dx + dy * dy <= RADIUS * RADIUS:
                        inside += 1
            alpha = (inside * 255 + samples // 2) // samples
            if alpha <= 0:
                data.extend((0, 0, 0, 0))
            else:
                data.extend((255, 255, 255, alpha))
    return bytes(data)


def format_array(data: bytes, width: int = 12) -> str:
    lines = []
    for offset in range(0, len(data), width):
        chunk = data[offset : offset + width]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return "\n".join(lines)


def make_source(pixels: bytes) -> str:
    return f"""/* Generated by tools/gen_switch_icon.py.  Do not edit. */
#include <stddef.h>

const int pacman_switch_icon_w = {WIDTH};
const int pacman_switch_icon_h = {HEIGHT};
const size_t pacman_switch_icon_len = {len(pixels)};

const unsigned char pacman_switch_icon[] = {{
{format_array(pixels)}
}};
"""


def png_chunk(kind: bytes, data: bytes) -> bytes:
    return (struct.pack(">I", len(data)) + kind + data +
            struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))


def encode_png(pixels: bytes) -> bytes:
    stride = WIDTH * 4
    raw = bytearray()
    for y in range(HEIGHT):
        raw.append(0)
        raw.extend(pixels[y * stride : (y + 1) * stride])
    return (b"\x89PNG\r\n\x1a\n" +
            png_chunk(b"IHDR", struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 6, 0, 0, 0)) +
            png_chunk(b"IDAT", zlib.compress(bytes(raw), 9)) +
            png_chunk(b"IEND", b""))


def write_if_changed(path: Path, text: str) -> bool:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    temporary.replace(path)
    return True


def write_bytes_if_changed(path: Path, data: bytes) -> bool:
    old = path.read_bytes() if path.exists() else None
    if old == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(data)
    temporary.replace(path)
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the switch knob icon.")
    parser.add_argument("-o", "--output", help="optional .c output path for debugging")
    parser.add_argument("--png", help="output .png path, e.g. assets/Default/icon/knob.png")
    args = parser.parse_args(argv)

    pixels = build_pixels()

    if args.output:
        output = Path(args.output)
        changed = write_if_changed(output, make_source(pixels))
        print(f"{output}{' 已生成' if changed else ' 已是最新'}（{WIDTH}x{HEIGHT}）")

    if args.png:
        png_path = Path(args.png)
        png_changed = write_bytes_if_changed(png_path, encode_png(pixels))
        print(f"{png_path}{' 已生成' if png_changed else ' 已是最新'}（{WIDTH}x{HEIGHT} PNG）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
