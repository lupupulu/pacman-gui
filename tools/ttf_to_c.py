#!/usr/bin/env python3
"""Embed a TrueType/OpenType font in a C translation unit.

The generated .c file defines a byte array and its length, so the font can be
linked into the executable and opened with SDL_IOFromConstMem() +
TTF_OpenFontIO() -- no font file is needed at runtime.

Example:

    python3 tools/ttf_to_c.py assets/PacmanPixel-ASCII.ttf \
        -o build/pacman_pixel_font.c \
        --symbol pacman_pixel_ttf

A separate header is optional (--header); by default only the .c is written.
Declare the symbols where you use them:

    extern const unsigned char pacman_pixel_ttf[];
    extern const size_t pacman_pixel_ttf_len;

    SDL_IOStream *io = SDL_IOFromConstMem(pacman_pixel_ttf,
                                          pacman_pixel_ttf_len);
    TTF_Font *font = TTF_OpenFontIO(io, true, 20.0f);
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

# sfnt magic numbers.  "OTTO" is CFF-flavoured OpenType; it embeds and loads
# just as well, but the script says so instead of pretending it is TrueType.
SFNT_MAGIC = {
    b"\x00\x01\x00\x00": "TrueType",
    b"OTTO": "OpenType/CFF",
    b"true": "Apple TrueType",
    b"typ1": "Apple Type 1",
}


def c_identifier(value: str, fallback: str = "font") -> str:
    """Turn an arbitrary string into a valid C identifier."""
    value = re.sub(r"[^0-9A-Za-z_]", "_", value)
    value = re.sub(r"_+", "_", value).strip("_")
    if not value:
        value = fallback
    if value[0].isdigit():
        value = "_" + value
    return value


def default_symbol(path: Path) -> str:
    stem = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", path.stem)
    stem = re.sub(r"[^0-9A-Za-z]+", "_", stem).strip("_").lower()
    return c_identifier(f"{stem or 'font'}_ttf")


def format_array(data: bytes, width: int) -> str:
    lines = []
    for offset in range(0, len(data), width):
        chunk = data[offset : offset + width]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return "\n".join(lines)


def write_if_changed(path: Path, text: str) -> bool:
    """Write text atomically, but keep mtime when the content is unchanged."""
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8", newline="\n")
    os.replace(temporary, path)
    return True


def make_header(symbol: str) -> str:
    guard = c_identifier(f"{symbol}_h").upper()
    length = f"{symbol}_len"
    return f"""/* Generated by tools/ttf_to_c.py.  Do not edit. */
#ifndef {guard}
#define {guard}

#include <stddef.h>

#ifdef __cplusplus
extern "C" {{
#endif

extern const unsigned char {symbol}[];
extern const size_t {length};

#ifdef __cplusplus
}}
#endif

#endif /* {guard} */
"""


def make_source(
    source_name: str,
    data: bytes,
    symbol: str,
    header: Path | None,
    output: Path,
) -> str:
    length = f"{symbol}_len"
    include = ""
    if header is not None:
        if header.parent == output.parent:
            include_name = header.name
        else:
            include_name = os.path.relpath(header, output.parent).replace(os.sep, "/")
        include = f'#include "{include_name}"\n\n'
    return f"""/* Generated by tools/ttf_to_c.py from {source_name}.
 * {len(data)} bytes.  Do not edit; rerun the generator instead.
 */
#include <stddef.h>

{include}const unsigned char {symbol}[] = {{
{format_array(data, 12)}
}};

const size_t {length} = sizeof({symbol});
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Convert a TTF/OTF file into a C byte array for embedding."
    )
    parser.add_argument("input", type=Path, help="input .ttf/.otf file")
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        help="output .c file (default: <input stem>.c next to the input)",
    )
    parser.add_argument(
        "--header",
        type=Path,
        help="also generate a header with extern declarations",
    )
    parser.add_argument(
        "--symbol",
        help="C symbol for the array (default: derived from the input filename)",
    )
    parser.add_argument(
        "--line-width",
        type=int,
        default=12,
        help="bytes per line in the generated array (default: 12)",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="only print errors",
    )
    args = parser.parse_args(argv)

    if args.line_width < 1:
        parser.error("--line-width must be at least 1")

    source = args.input
    if not source.is_file():
        parser.error(f"input file not found: {source}")

    data = source.read_bytes()
    if not data:
        parser.error(f"input file is empty: {source}")

    flavour = SFNT_MAGIC.get(data[:4])
    if flavour is None:
        parser.error(
            f"{source} does not look like a TTF/OTF file "
            f"(first bytes: {data[:4].hex(' ')})"
        )

    symbol = c_identifier(args.symbol) if args.symbol else default_symbol(source)
    output = args.output or source.with_suffix(".c")
    if output.suffix.lower() != ".c":
        parser.error("--output must end in .c")
    if args.header and args.header.suffix.lower() not in (".h", ".hpp"):
        parser.error("--header must end in .h or .hpp")

    source_text = make_source(source.name, data, symbol, args.header, output)
    changed = write_if_changed(output, source_text)

    header_changed = False
    if args.header:
        header_changed = write_if_changed(args.header, make_header(symbol))

    if not args.quiet:
        print(f"{source}: {len(data)} bytes ({flavour})")
        print(f"  {output}: {'written' if changed else 'unchanged'}  symbol={symbol}")
        if args.header:
            print(
                f"  {args.header}: "
                f"{'written' if header_changed else 'unchanged'}"
            )
    return 0


if __name__ == "__main__":
    sys.exit(main())
