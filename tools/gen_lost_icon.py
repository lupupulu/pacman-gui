#!/usr/bin/env python3
"""生成内置的 lost 图标（一个问号），并输出成可编译的 C 源文件。

图标是 16x16 的像素图放大 4 倍得到的 64x64 RGBA 数据：
白色问号 + 透明背景。运行时用 SDL_CreateSurfaceFrom() 直接引用这段数据，
不需要 PNG 解码器，也不需要外部图标文件。

`--png` 可以额外输出一份 PNG 副本，默认主题使用它：
    assets/Default/icon/lost.png

用法：
    python3 tools/gen_lost_icon.py -o build/lost_icon.c \
        --png assets/Default/icon/lost.png
"""

from __future__ import annotations

import argparse
import struct
import sys
import zlib
from pathlib import Path

# 16x16 像素图；'#' 是问号，'.' 是透明
PATTERN = (
    "................",
    "................",
    ".....#####......",
    "....##...##.....",
    "....##...##.....",
    "........##......",
    ".......##.......",
    "......##........",
    "......##........",
    "................",
    "......##........",
    "......##........",
    "................",
    "................",
    "................",
    "................",
)

SCALE = 4
WIDTH = len(PATTERN[0]) * SCALE
HEIGHT = len(PATTERN) * SCALE

FOREGROUND = (255, 255, 255, 255)
TRANSPARENT = (0, 0, 0, 0)


def build_pixels() -> bytes:
    data = bytearray()
    for row in PATTERN:
        for _ in range(SCALE):
            for cell in row:
                color = FOREGROUND if cell == "#" else TRANSPARENT
                for _ in range(SCALE):
                    data.extend(color)
    return bytes(data)


def format_array(data: bytes, width: int = 12) -> str:
    lines = []
    for offset in range(0, len(data), width):
        chunk = data[offset : offset + width]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return "\n".join(lines)


def make_source(pixels: bytes) -> str:
    return f"""/* Generated by tools/gen_lost_icon.py.  Do not edit. */
#include <stddef.h>

const int pacman_lost_icon_w = {WIDTH};
const int pacman_lost_icon_h = {HEIGHT};
const size_t pacman_lost_icon_len = {len(pixels)};

const unsigned char pacman_lost_icon[] = {{
{format_array(pixels)}
}};
"""


def write_if_changed(path: Path, text: str) -> bool:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    # Path.write_text(newline=...) 需要 Python 3.10，macOS 自带 3.9 没有这个参数
    with temporary.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    temporary.replace(path)
    return True


def png_chunk(kind: bytes, data: bytes) -> bytes:
    return (struct.pack(">I", len(data)) + kind + data +
            struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))


def encode_png(pixels: bytes) -> bytes:
    """把紧凑的 RGBA 数据编码成 8-bit RGBA PNG（只用标准库）。"""
    stride = WIDTH * 4
    raw = bytearray()
    for y in range(HEIGHT):
        raw.append(0)  # filter type: None
        raw.extend(pixels[y * stride : (y + 1) * stride])

    return (b"\x89PNG\r\n\x1a\n" +
            png_chunk(b"IHDR", struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 6, 0, 0, 0)) +
            png_chunk(b"IDAT", zlib.compress(bytes(raw), 9)) +
            png_chunk(b"IEND", b""))


def write_bytes_if_changed(path: Path, data: bytes) -> bool:
    old = path.read_bytes() if path.exists() else None
    if old == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(data)
    temporary.replace(path)
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the built-in lost icon C source.")
    parser.add_argument("-o", "--output", default="build/lost_icon.c", help="output .c path")
    parser.add_argument("--png", help="optional .png copy, e.g. assets/Default/icon/lost.png")
    args = parser.parse_args(argv)

    pixels = build_pixels()
    output = Path(args.output)
    changed = write_if_changed(output, make_source(pixels))
    if changed:
        print(f"已生成 {output}（{WIDTH}x{HEIGHT}, {len(pixels)} 字节）")
    else:
        print(f"{output} 已是最新（{WIDTH}x{HEIGHT}）")

    if args.png:
        png_path = Path(args.png)
        png_changed = write_bytes_if_changed(png_path, encode_png(pixels))
        if png_changed:
            print(f"已生成 {png_path}（{WIDTH}x{HEIGHT} PNG）")
        else:
            print(f"{png_path} 已是最新（{WIDTH}x{HEIGHT} PNG）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
